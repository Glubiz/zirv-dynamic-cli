    #[test]
    fn generation_is_idempotent_and_byte_stable() {
        let (dir, _guard) = repo();
        write_canonical(dir.path(), "common.md", "Always run the full test suite.");
        write_canonical(dir.path(), "claude.md", "Prefer the native tool-use loop.");

        let (code1, _) = run_sync(&generate_args(false), dir.path());
        assert_eq!(code1, 0);
        let first_bytes = fs::read(native_claude_path(dir.path())).expect("read");

        let (code2, out2) = run_sync(&generate_args(false), dir.path());
        assert_eq!(code2, 0);
        assert!(out2.contains("unchanged"), "got {out2}");
        let second_bytes = fs::read(native_claude_path(dir.path())).expect("read");

        assert_eq!(
            first_bytes, second_bytes,
            "regenerating an already-managed, unchanged file must be byte-stable"
        );
    }

