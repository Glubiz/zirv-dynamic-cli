//! `zirv context <verb>` -- a top-level command family (issue #45, "Context
//! 7/8"), sibling to `zirv ctx` rather than one of its verbs: intercepted
//! against raw argv in `main.rs` exactly like `ctx`/`chat`/`agent` (see
//! `is_top_level_context` there), because this is not an alias for anything
//! under `zirv ctx` -- it is its own command family, with `sync` as its
//! first verb.
//!
//! **Goal.** `.zirv/context/` (`context.rs`) is the canonical source of
//! project instructions for every Zirv-launched harness (`compile.rs` reads
//! it at every launch). Claude and Codex can also be launched *directly*,
//! outside zirv entirely, in which case only their own native files --
//! `CLAUDE.md`, `AGENTS.md` -- are ever read. `sync` is the explicit,
//! opt-in bridge between the two: it never runs on its own (no autogeneration
//! at launch, no side effect from `compile::compile`), and every mode it
//! offers is a deliberate, separately-named choice -- never an implicit
//! side effect of another one.
//!
//! **Three modes, mutually exclusive** (`SyncArgs`'s `mode` `ArgGroup`):
//! - default / `--report`: inspect and report differences. Never writes.
//! - `--import`: native `CLAUDE.md`/`AGENTS.md` -> canonical
//!   `.zirv/context/{claude,codex}.md`.
//! - `--generate`: canonical `.zirv/context/*.md` -> managed `CLAUDE.md`/
//!   `AGENTS.md`.
//!
//! **The central safety property.** `--generate` must never silently
//! overwrite a hand-maintained native file. Every generated file's first
//! line is [`MANAGED_MARKER`], a stable, deterministic, machine-readable
//! header; `--generate` refuses to touch any existing native file whose
//! content does not start with it (`is_managed`), and reports the refusal
//! plainly rather than failing loudly or overwriting anyway. Only an
//! explicit `--force` -- the user's own deliberate choice, never a default
//! -- lifts that refusal, for both `--generate` (replace an unmanaged
//! native file) and `--import` (replace canonical content that already
//! differs from the native file being imported).
//!
//! **Determinism and idempotency.** [`render_generated`] is a pure function
//! of its two inputs (no clock, no environment read, the same discipline
//! `compile.rs`/`rot.rs` hold themselves to): the same canonical content
//! always renders to byte-identical output, and generating twice in a row
//! with nothing changed is a true no-op (`generate_one` compares against
//! the file already on disk before writing anything).
//!
//! **Content routing.** [`render_generated`] takes the canonical common text
//! and exactly one harness-specific text; the two call sites in
//! `run_generate` pass `claude.md`'s content only into the `CLAUDE.md`
//! render and `codex.md`'s content only into the `AGENTS.md` render, so
//! there is no code path through which one harness's canonical addition
//! could reach the other's generated file.
//!
//! **Instructions only, never enforcement.** A generated file is prose,
//! nothing else: [`render_generated`] never touches `policy::EffectivePolicy`
//! or any `Support` state, and carries no permission/sandbox/security claim,
//! because outside zirv there is no zirv process to enforce one -- the same
//! "advisory, not enforcement" line `policy.rs`'s own module doc draws for
//! Markdown instructions in general.

